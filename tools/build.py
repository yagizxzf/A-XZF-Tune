"""Dependency-free deterministic Roblox XML packaging. Python 3.10+."""
from pathlib import Path
import argparse
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"


def sources():
    result = []
    groups = [("src/Shared", "ReplicatedStorage.AXZF.Shared"),
              ("src/Server", "ServerScriptService.AXZFServer"),
              ("src/Client", "StarterPlayer.StarterPlayerScripts"),
              ("ui/runtime", "ReplicatedStorage.AXZF.UI"),
              ("vfx/runtime", "ReplicatedStorage.VFX"),
              ("examples", "ServerStorage.AXZFExamples"),
              ("tests", "ServerStorage.AXZFTests")]
    for folder, prefix in groups:
        for path in sorted((ROOT / folder).glob("*.luau")):
            name = path.stem
            cls = "ModuleScript"
            if name.endswith(".server"):
                cls, name = "Script", name[:-7]
            elif name.endswith(".client"):
                cls, name = "LocalScript", name[:-7]
            parent = "ServerScriptService" if path.name == "Demo.server.luau" else prefix
            if folder == "tests" and cls == "Script":
                parent = "ServerScriptService"
            elif folder == "tests" and cls == "LocalScript":
                parent = "StarterPlayer.StarterPlayerScripts"
            result.append(dict(path=str(path.relative_to(ROOT)).replace("\\", "/"),
                               target=parent + "." + name, className=cls,
                               source=path.read_text(encoding="utf-8")))
    return result


def prop(item, kind, name, text):
    element = ET.SubElement(item.find("Properties"), kind, name=name)
    element.text = text


def make_xml(entries, kit=False):
    root = ET.Element("roblox", version="4")
    container = root
    if kit:
        container = ET.SubElement(root, "Item", {"class": "Model", "referent": "AXZFPackage"})
        ET.SubElement(container, "Properties")
        prop(container, "string", "Name", "A-XZF-Tune")
    lookup = {}
    def ensure(path, cls="Folder"):
        if path in lookup:
            return lookup[path]
        parts = path.split(".")
        parent = ensure(".".join(parts[:-1])) if len(parts) > 1 else container
        if len(parts) == 1:
            cls = "Folder" if kit else parts[0]
        elif path == "StarterPlayer.StarterPlayerScripts":
            cls = "Folder" if kit else "StarterPlayerScripts"
        item = ET.SubElement(parent, "Item", {"class": cls, "referent": "AXZF"+str(len(lookup))})
        ET.SubElement(item, "Properties")
        prop(item, "string", "Name", parts[-1])
        lookup[path] = item
        return item
    for entry in entries:
        item = ensure(entry["target"], entry["className"])
        prop(item, "ProtectedString", "Source", entry["source"])
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


def build():
    BUILD.mkdir(exist_ok=True)
    entries = sources()
    runtime = [e for e in entries if e["path"].startswith(("src/", "ui/runtime/", "vfx/runtime/")) or e["path"] == "examples/VehicleTune.luau"]
    (BUILD / "A-XZF-Tune.rbxmx").write_bytes(make_xml(runtime, kit=True))
    (BUILD / "A-XZF-Tune-Demo.rbxlx").write_bytes(make_xml(entries))
    manifest = [{k: v for k, v in e.items() if k != "source"} |
                {"sha256": hashlib.sha256(e["source"].encode()).hexdigest()} for e in entries]
    (BUILD / "manifest.json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8")
    # Script text is also useful in Studio Command Bar / plugin workflows.
    lines = ["-- Generated by tools/build.py. Installs only AXZF-owned paths; does not publish."]
    for entry in entries:
        path = entry["target"].split(".")
        lines.append("do local parent=game:GetService("+json.dumps(path[0])+")")
        for name in path[1:-1]:
            cls = "StarterPlayerScripts" if name == "StarterPlayerScripts" else "Folder"
            lines.append("local next=parent:FindFirstChild("+json.dumps(name)+") or Instance.new("+json.dumps(cls)+") next.Name="+json.dumps(name)+" next.Parent=parent parent=next")
        name = json.dumps(path[-1])
        lines.append("local s=parent:FindFirstChild("+name+") or Instance.new("+json.dumps(entry["className"])+") assert(s.ClassName=="+json.dumps(entry["className"])+",'AXZF path collision') s.Name="+name)
        delimiter = "==="
        while "]"+delimiter+"]" in entry["source"]:
            delimiter += "="
        lines.append("s.Source=["+delimiter+"["+entry["source"]+"]"+delimiter+"] s.Parent=parent end")
    (BUILD / "InstallDemo.luau").write_text("\n".join(lines)+"\n", encoding="utf-8")
    return entries


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--sources", action="store_true", help="emit full source manifest for Studio tooling")
    args = parser.parse_args()
    entries = build()
    print(json.dumps(entries) if args.sources else f"Built runtime model and demo place: {len(entries)} scripts")
